export const STRINGS: Record<UiLang, Strings> = { en, ta, hi, or }

const KEY = 'sahpaathi.ui-lang'

/** The saved choice, else the phone's language if we have it, else English. */
export function initialLang(): UiLang {
  try {
    const saved = localStorage.getItem(KEY) as UiLang | null
    if (saved && saved in STRINGS) return saved
  } catch {
    // storage blocked: fall through
  }
  const phone = (navigator.language || 'en').slice(0, 2) as UiLang
  return phone in STRINGS ? phone : 'en'
}

export function saveLang(lang: UiLang) {
  try {
    localStorage.setItem(KEY, lang)
  } catch {
    // not remembered; the picker still works for this visit
  }
}
